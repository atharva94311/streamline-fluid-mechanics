import { useRef } from 'react'
import { easeInOut, expm3, useLoop, type P2 } from './shared'

/**
 * Recreation of Lecture 9 slides 2–3: a fluid particle at time t and at t + δt, and the four elementary
 * motions drawn separately. Each panel animates the element from its initial to its final state.
 */

type M2 = [number, number, number, number] // [m11, m12, m21, m22]

interface PanelDef {
  key: string
  title: string
  note: string
  /** Deformation/rotation of the element about its centre after progress s ∈ [0, 1]. */
  M: (s: number) => M2
}

const I: M2 = [1, 0, 0, 1]

function expm2(a: number, b: number, c: number, d: number): M2 {
  const E = expm3([a, b, 0, c, d, 0, 0, 0, 0])
  return [E[0], E[1], E[3], E[4]]
}

const PANELS: PanelDef[] = [
  { key: 'translation', title: 'Translation', note: 'same size, same orientation — only the position changes', M: () => I },
  {
    key: 'rotation',
    title: 'Rotation',
    note: 'orientation changes (here 45° counter-clockwise); size and shape do not',
    M: (s) => {
      const th = (Math.PI / 4) * s
      return [Math.cos(th), -Math.sin(th), Math.sin(th), Math.cos(th)]
    },
  },
  {
    key: 'linear',
    title: 'Linear deformation',
    note: 'stretched in x, shortened in y — edges stay parallel to the axes, corners stay 90°',
    M: (s) => [1 + 0.42 * s, 0, 0, 1 - 0.4 * s],
  },
  {
    key: 'angular',
    title: 'Angular deformation',
    note: 'the originally perpendicular edges tilt toward each other — the right angle is lost',
    M: (s) => [1, 0.27 * s, 0.27 * s, 1],
  },
]

/** General motion (slide 2): all four at once, generated by a linear velocity field. */
const generalM = (s: number): M2 => expm2(0.35 * s, -0.62 * s, 0.95 * s, -0.25 * s)

const W = 200
const H = 150
const ORIGIN: P2 = [16, 136] // screen position of the axes' origin
const C0: P2 = [58, 98] // initial centre (screen)
const C1: P2 = [150, 44] // final centre (screen)
const HALF = 17 // half side of the square (screen px)

/** Map an element corner (unit square coordinates ±1) to screen space with matrix M (math y-up) and centre c. */
function corner(M: M2, c: P2, ex: number, ey: number): P2 {
  const x = HALF * (M[0] * ex + M[1] * ey)
  const y = HALF * (M[2] * ex + M[3] * ey)
  return [c[0] + x, c[1] - y]
}

function poly(M: M2, c: P2): string {
  return ([[-1, -1], [1, -1], [1, 1], [-1, 1]] as P2[]).map(([ex, ey]) => corner(M, c, ex, ey).map((v) => v.toFixed(2)).join(',')).join(' ')
}

function Axes() {
  return (
    <g>
      <line x1={ORIGIN[0]} y1={ORIGIN[1]} x2={W - 6} y2={ORIGIN[1]} stroke="var(--ink-3)" strokeWidth={1.1} />
      <line x1={ORIGIN[0]} y1={ORIGIN[1]} x2={ORIGIN[0]} y2={6} stroke="var(--ink-3)" strokeWidth={1.1} />
      <text x={W - 8} y={ORIGIN[1] + 11} textAnchor="end" fontSize={11} fontStyle="italic" className="fill-ink-3">
        x
      </text>
      <text x={ORIGIN[0] - 8} y={12} textAnchor="middle" fontSize={11} fontStyle="italic" className="fill-ink-3">
        y
      </text>
    </g>
  )
}

function Panel({ M, s, color, labels }: { M: (s: number) => M2; s: number; color: string; labels?: boolean }) {
  const e = easeInOut(Math.min(1, Math.max(0, s)))
  const c: P2 = [C0[0] + (C1[0] - C0[0]) * e, C0[1] + (C1[1] - C0[1]) * e]
  const Mf = M(1)
  const Ms = M(e)
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="block h-auto w-full" role="img" aria-label="fluid element moving and deforming">
      <Axes />
      {/* initial and final outlines */}
      <polygon points={poly(I, C0)} fill="none" stroke={color} strokeWidth={1.4} />
      <circle cx={C0[0]} cy={C0[1]} r={2.2} fill={color} />
      <polygon points={poly(Mf, C1)} fill="none" stroke={color} strokeWidth={1} strokeDasharray="3 3" opacity={0.55} />
      {/* moving element */}
      <polygon points={poly(Ms, c)} fill={color} fillOpacity={0.14} stroke={color} strokeWidth={1.8} />
      <circle cx={c[0]} cy={c[1]} r={2.4} fill={color} />
      {labels ? (
        <g fontSize={10.5} className="fill-ink-2">
          <text x={C0[0]} y={C0[1] + HALF + 13} textAnchor="middle">
            particle at time <tspan fontStyle="italic">t</tspan>
          </text>
          <text x={C1[0]} y={C1[1] + 34} textAnchor="middle">
            at <tspan fontStyle="italic">t</tspan> + δ<tspan fontStyle="italic">t</tspan>
          </text>
        </g>
      ) : null}
    </svg>
  )
}

export function FourMotionsFigure() {
  const ref = useRef<HTMLDivElement>(null)
  const { s } = useLoop(ref, 2.4, { hold: 1.2 })
  return (
    <div ref={ref} className="space-y-3">
      <div className="grid items-center gap-3 sm:grid-cols-[1fr_1.1fr]">
        <div className="rounded-xl border border-line bg-surface-2/50 p-2">
          <Panel M={generalM} s={s} color="var(--plot-3)" labels />
        </div>
        <div className="text-sm text-ink-2">
          <div className="mb-1 font-semibold text-ink">General motion (slide 2)</div>
          In a time δ<i>t</i> a small particle generally does <b>all four</b> things at once: it moves to a new place, turns, and
          changes both its size and its angles. The four panels below isolate each motion (slide 3).
        </div>
      </div>
      <div className="grid grid-cols-2 gap-2 sm:gap-3">
        {PANELS.map((p, i) => (
          <div key={p.key} className="rounded-xl border border-line bg-surface-2/50 p-2">
            <Panel M={p.M} s={s} color={['var(--plot-1)', 'var(--plot-6)', 'var(--plot-2)', 'var(--plot-4)'][i]} />
            <div className="mt-1 px-1 text-[13px] font-semibold text-ink">{p.title}</div>
            <div className="px-1 text-[11.5px] leading-snug text-ink-3">{p.note}</div>
          </div>
        ))}
      </div>
    </div>
  )
}
