/** Merge repeated runs (same x within tol) by averaging, keeping x sorted. */
export function mergeRuns(pts: Pt[], tol = 0.004): Pt[] {
  const s = [...pts].sort((a, b) => a[0] - b[0])
  const out: { x: number; y: number; n: number }[] = []
  for (const [x, y] of s) {
    const last = out[out.length - 1]
    if (last && Math.abs(x - last.x / last.n) <= tol) {
      last.x += x
      last.y += y
      last.n += 1
    } else out.push({ x, y, n: 1 })
  }
  return out.map((o) => [o.x / o.n, o.y / o.n])
}

/** Piecewise-linear interpolation through sorted points (clamped at the ends). */
export function interp(pts: Pt[], x: number): number {
  if (!pts.length) return NaN
  if (x <= pts[0][0]) return pts[0][1]
  const n = pts.length
  if (x >= pts[n - 1][0]) return pts[n - 1][1]
  for (let i = 1; i < n; i++) {
    if (x <= pts[i][0]) {
      const [x0, y0] = pts[i - 1]
      const [x1, y1] = pts[i]
      return y0 + ((y1 - y0) * (x - x0)) / (x1 - x0)
    }
  }
  return pts[n - 1][1]
}

