export function bezierPoints(segs: Bez[], n = 40): Pt[] {
  const out: Pt[] = []
  segs.forEach((b, k) => {
    for (let i = k === 0 ? 0 : 1; i <= n; i++) {
      const t = i / n
      const u = 1 - t
      const a = u * u * u
      const bb = 3 * u * u * t
      const c = 3 * u * t * t
      const d = t * t * t
      out.push([a * b[0][0] + bb * b[1][0] + c * b[2][0] + d * b[3][0], a * b[0][1] + bb * b[1][1] + c * b[2][1] + d * b[3][1]])
    }
  })
  return out
}

/** SVG path string for a Bézier list in a box (y flipped). */
export function bezierPath(segs: Bez[], X: (x: number) => number, Y: (y: number) => number): string {
  return segs
    .map((b, k) => `${k === 0 ? `M${X(b[0][0])},${Y(b[0][1])} ` : ''}C${X(b[1][0])},${Y(b[1][1])} ${X(b[2][0])},${Y(b[2][1])} ${X(b[3][0])},${Y(b[3][1])}`)
    .join(' ')
}

